def peek_next_promo(state: Dict[str, Any]) -> Dict[str, Any]:
    """متن بعدی را بدون commit کردن برمی‌گرداند؛ فقط بعد از ارسال موفق باید
    commit_promo_index صدا زده شود (بخش ۹.۴: تعهد فقط پس از تأیید ارسال)."""
    try:
        idx = int(state.get("index", 0)) % len(PROMO_BANK)
    except (TypeError, ValueError):
        idx = 0
    return {"index": idx, "text": PROMO_BANK[idx]}


def commit_promo_index(state: Dict[str, Any], used_index: int) -> Dict[str, Any]:
    """فقط بعد از تأیید ارسال موفق فراخوانی شود. اگر ارسال شکست خورد، این
    تابع را صدا نزن تا متن مصرف‌نشده از چرخه حذف نشود."""
    state = dict(state)
    state["index"] = (int(used_index) + 1) % len(PROMO_BANK)
    return state


def append_promo_footer(message_text: str, promo_text: str) -> str:
    """تبلیغ همیشه به‌صورت Footer بعد از متن اصلی اضافه می‌شود؛ هرگز جایگزین
    یا پیش از محتوای اصلی قرار نمی‌گیرد. پیام مستقل جدید ساخته نمی‌شود."""
    return "{}\n\n{}".format(message_text.rstrip(), promo_text)
